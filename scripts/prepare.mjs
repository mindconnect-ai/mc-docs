// Stages everything the Docusaurus config needs from the project checkouts
// into .generated/ (gitignored). Runs before `start`, `build` and snapshots.
//
//   .generated/sidebars/<id>.js        the project's sidebar, with links adapted to the portal
//   .generated/static/_assets/<id>/img the project's static/img (served at /_assets/<id>/img/)
//   .generated/stub/<id>/index.md      placeholder when a checkout is missing
//   .generated/sources.json            what was found where (read by docusaurus.config.js)
//
// A missing project never fails the build: it gets a stub page and a warning.

import {cpSync, existsSync, mkdirSync, rmSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {GENERATED, envName, resolveAll} from './sources.mjs';

function rewriteUrl(url, rewrites = []) {
  for (const [from, to] of rewrites) {
    if (url.startsWith(from)) return to + url.slice(from.length);
  }
  return url;
}

function rewriteSidebarItems(items, rewrites) {
  if (Array.isArray(items)) return items.map((i) => rewriteSidebarItems(i, rewrites));
  if (items && typeof items === 'object') {
    const out = {};
    for (const [k, v] of Object.entries(items)) {
      out[k] = k === 'href' && typeof v === 'string' ? rewriteUrl(v, rewrites) : rewriteSidebarItems(v, rewrites);
    }
    return out;
  }
  return items;
}

const AUTOGENERATED = {docs: [{type: 'autogenerated', dirName: '.'}]};

async function loadSidebar(file) {
  if (file.endsWith('.json')) {
    const {readFileSync} = await import('node:fs');
    return JSON.parse(readFileSync(file, 'utf8'));
  }
  // Cache-bust so `npm start` restarts pick up sidebar edits.
  const mod = await import(`${pathToFileURL(file).href}?t=${Date.now()}`);
  return mod.default ?? mod;
}

function writeStub(project) {
  const dir = join(GENERATED, 'stub', project.id);
  mkdirSync(dir, {recursive: true});
  const how = project.private
    ? `In CI this section needs the \`DOCS_READ_TOKEN\` secret (read access to \`${project.repo}\`).`
    : `CI checks \`${project.repo}\` out automatically.`;
  writeFileSync(
    join(dir, 'index.md'),
    `---
title: ${project.label}
slug: /
---

# ${project.label}

${project.tagline}

The documentation for ${project.label} is not available in this build.

The source is \`${project.docsPath}\` in [${project.repo}](https://github.com/${project.repo}).
${how} Locally, point \`${envName(project.id)}\` at a checkout of the repository.
`,
  );
  return dir;
}

export async function prepare({quiet = false} = {}) {
  rmSync(GENERATED, {recursive: true, force: true});
  mkdirSync(join(GENERATED, 'sidebars'), {recursive: true});
  mkdirSync(join(GENERATED, 'static', '_assets'), {recursive: true});
  // An empty static directory makes the static-file copy fail; keep one file in it.
  writeFileSync(join(GENERATED, 'static', '_assets', '.keep'), '');

  const manifest = {};
  for (const src of resolveAll()) {
    const {project} = src;
    const sidebarOut = join(GENERATED, 'sidebars', `${project.id}.js`);
    let sidebars = AUTOGENERATED;
    let docsDir = src.docsDir;
    let available = Boolean(docsDir);

    if (!available) {
      docsDir = writeStub(project);
      console.warn(
        `[prepare] WARNING: ${project.id}: no checkout found (${project.repo}, ${project.docsPath}). ` +
          `Building a stub page. Set ${envName(project.id)} or check out into sources/${project.id}.`,
      );
    } else {
      if (src.sidebarFile) {
        try {
          sidebars = rewriteSidebarItems(await loadSidebar(src.sidebarFile), project.urlRewrites);
        } catch (e) {
          console.warn(`[prepare] WARNING: ${project.id}: cannot load ${src.sidebarFile} (${e.message}); using an autogenerated sidebar.`);
        }
      }
      if (src.staticImgDir) {
        cpSync(src.staticImgDir, join(GENERATED, 'static', '_assets', project.id, 'img'), {recursive: true});
      }
      if (!quiet) console.log(`[prepare] ${project.id}: ${src.repoDir} (${src.origin})`);
    }

    writeFileSync(sidebarOut, `// Generated by scripts/prepare.mjs. Do not edit.\nexport default ${JSON.stringify(sidebars, null, 2)};\n`);
    manifest[project.id] = {
      available,
      origin: src.origin,
      repoDir: src.repoDir,
      docsDir,
      sidebarPath: sidebarOut,
      sidebarIds: Object.keys(sidebars),
      hasLicensePage: available && existsSync(join(docsDir, 'license.md')),
    };
  }
  writeFileSync(join(GENERATED, 'sources.json'), JSON.stringify(manifest, null, 2));
  return manifest;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  prepare().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
